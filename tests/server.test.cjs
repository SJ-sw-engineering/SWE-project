const assert = require('node:assert/strict');
const vm = require('node:vm');
const fs = require('node:fs');
const path = require('node:path');
const memory = new Map();
const calls = [];
let respond;
const local = { me: () => ({ username: 'local' }), getPost: async () => ({ id: 99 }), savePost: async () => 100 };
const context = vm.createContext({
  StudyMate: local, URLSearchParams, AbortController, TypeError, setTimeout, clearTimeout,
  sessionStorage: { getItem: key => memory.get(key), setItem: (key, value) => memory.set(key, value), removeItem: key => memory.delete(key) },
  fetch: async (url, options) => { calls.push({ url, options }); return respond(url, options); }
});
vm.runInContext(fs.readFileSync(path.join(__dirname, '../js/server.js'), 'utf8'), context);
const api = context.StudyMate;
const post = { id: 1, title: '서버 모집글', author_name: '팀장', category: 'Web', target_size: 4, current_size: null, status: null, created_at: null };
const success = body => ({ ok: true, json: async () => body });
(async () => {
  assert.equal(context.StudyMateSource.mode(), 'server');
  assert.equal(api.me(), null);
  respond = () => success({ items: [post], total: 7, page: 2, page_size: 6 });
  const list = await api.postsPage({ page: 2, keyword: 'C++ & 웹', category: 'Web/Frontend', status: 'CLOSED' });
  const requested = new URL(calls.at(-1).url);
  assert.equal(requested.searchParams.get('keyword'), 'C++ & 웹');
  assert.equal(requested.searchParams.get('category'), 'Web/Frontend');
  assert.equal(requested.searchParams.get('page'), '2');
  assert.equal(requested.searchParams.get('status'), 'CLOSED');
  assert.equal(calls.at(-1).options.credentials, 'omit');
  assert.equal(list.items[0].status, 'UNKNOWN');
  assert.equal(list.items[0].current_size, null);
  respond = () => success({ ...post, content: '<script>test</script>' });
  assert.equal((await api.getPost(1)).content, '<script>test</script>');
  const count = calls.length;
  await assert.rejects(api.getPost('../users'), /올바른/);
  assert.equal(calls.length, count);
  respond = () => ({ ok: false, status: 404 });
  await assert.rejects(api.getPost(1), /찾을 수/);
  respond = () => ({ ok: false, status: 503 });
  await assert.rejects(api.postsPage(), /503/);
  respond = () => { throw new TypeError('Failed to fetch'); };
  await assert.rejects(api.postsPage(), /CORS/);
  respond = () => success({ items: {}, total: 1 });
  await assert.rejects(api.postsPage(), /응답 형식/);
  respond = () => success({ items: [], total: 0, page: 1, page_size: 6 });
  assert.equal((await api.postsPage()).items.length, 0);
  const abort = new AbortController();
  respond = (_url, options) => new Promise((_resolve, reject) => options.signal.addEventListener('abort', () => reject(new Error('cancelled'))));
  const pending = api.postsPage({}, abort.signal); abort.abort();
  await assert.rejects(pending, /cancelled/);
  await assert.rejects(api.savePost({}), /연결되지/);
  context.StudyMateSource.setMode('local');
  assert.equal(api.me().username, 'local');
  assert.equal((await api.getPost(99)).id, 99);
  assert.equal(await api.savePost({}), 100);
  context.StudyMateSource.setMode('server');
  assert.equal(api.me(), null);
  const user = { username: 'server_user', name: '서버 사용자', created_at: null };
  const authResponse = { access_token: 'test-only-token', token_type: 'bearer', expires_in: 1800, user };
  respond = url => success(url.endsWith('/api/auth/login') ? authResponse : user);
  await api.login('server_user', 'test-only-password');
  assert.equal(api.me().username, 'server_user');
  const loginCall = calls.find(c => c.url.endsWith('/api/auth/login'));
  assert.equal(loginCall.options.method, 'POST');
  assert.equal(loginCall.options.headers['Content-Type'], 'application/json');
  assert.equal(JSON.parse(loginCall.options.body).password, 'test-only-password');
  assert.equal(loginCall.options.headers.Authorization, undefined);
  assert.equal(calls.at(-1).options.headers.Authorization, 'Bearer test-only-token');
  assert.equal(calls.at(-1).options.cache, 'no-store');
  assert.ok(!memory.get('studymate.server.auth').includes('test-only-password'));
  respond = () => success({ items: [], total: 0, page: 1, page_size: 6 });
  await api.postsPage();
  assert.equal(calls.at(-1).options.headers.Authorization, undefined);
  context.StudyMateSource.setMode('local');
  assert.equal(api.me().username, 'local');
  context.StudyMateSource.setMode('server');
  assert.equal(api.me().username, 'server_user');
  respond = () => ({ ok: false, status: 401 });
  await assert.rejects(api.refreshMe(), /만료/);
  assert.equal(api.me(), null);
  await assert.rejects(api.login('server_user', 'wrong'), /올바르지/);
  respond = () => ({ ok: false, status: 422 });
  await assert.rejects(api.login('server_user', 'wrong'), /입력 형식/);
  respond = url => success(url.endsWith('/api/auth/login') ? authResponse : user);
  await api.login('server_user', 'test-only-password');
  const saved = JSON.parse(memory.get('studymate.server.auth'));
  memory.set('studymate.server.auth', JSON.stringify({ ...saved, expires_at: Date.now() - 1 }));
  assert.equal(api.me(), null);
  assert.ok(!memory.has('studymate.server.auth'));
  memory.set('studymate.server.auth', 'broken json');
  assert.equal(api.me(), null);
  respond = url => url.endsWith('/api/auth/login') ? success(authResponse) : Promise.reject(new TypeError('network'));
  await assert.rejects(api.login('server_user', 'test-only-password'), /CORS/);
  assert.equal(api.me(), null);
  respond = url => success(url.endsWith('/api/auth/login') ? authResponse : user);
  await api.login('server_user', 'test-only-password');
  let resolveMe;
  respond = () => new Promise(resolve => { resolveMe = resolve; });
  const stale = api.refreshMe();
  api.logout();
  resolveMe(success(user));
  assert.equal(await stale, null);
  assert.equal(api.me(), null);
  console.log('PASS: JSON login, Bearer profile, isolated session, no password persistence, logout, expiry, 401/422/network errors and stale profile response');
  console.log('PASS: server parameters/pagination, null handling, errors, cancellation, unsupported actions and local/server isolation');
})().catch(error => { console.error(error); process.exitCode = 1; });
