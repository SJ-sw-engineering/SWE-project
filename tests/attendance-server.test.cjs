const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const memory = new Map();
const calls = [];
const user = { username: 'team_leader', name: '팀장', created_at: null };
const session = { id: 3, post_id: 10, device_id: 2, status: 'OPEN', display_ack: false, expiry_time: new Date(Date.now()+300000).toISOString(), my_record: null };
let respond;
const ok = body => ({ ok: true, json: async () => body });
const ctx = vm.createContext({ StudyMate: {}, URLSearchParams, AbortController, TypeError, setTimeout, clearTimeout, sessionStorage: { getItem: k => memory.get(k), setItem: (k,v) => memory.set(k,String(v)), removeItem: k => memory.delete(k) }, fetch: async (url, options) => { const c = { path: new URL(url).pathname, ...options }; calls.push(c); return respond(c); } });
vm.runInContext(fs.readFileSync(path.join(__dirname, '../js/server.js'),'utf8'),ctx);
const api = ctx.StudyMate;
(async () => {
  respond = c => ok(c.path.endsWith('/login') ? { access_token: 'fake-token', token_type: 'bearer', expires_in: 1800, user } : user);
  await api.login('team_leader','test-password');
  respond = () => ok([{ id: 2, post_id: 10, last_ack: null, device_credential: 'must-be-removed' }]);
  assert.equal((await api.devices(10))[0].device_credential, undefined);
  respond = () => ok({ id: 2, post_id: 10, device_credential: 'test-only-device-key' });
  assert.equal((await api.registerDevice(10)).device_credential, 'test-only-device-key');
  assert.equal(calls.at(-1).method, 'POST');
  assert.equal(calls.at(-1).body, undefined);
  assert.ok(!JSON.stringify([...memory]).includes('test-only-device-key'));
  respond = () => ok({ ...session, code: '000047' });
  assert.equal((await api.startAttendance(10,'2')).code, undefined);
  assert.equal(calls.at(-1).path, '/api/posts/10/attendance-sessions');
  assert.deepEqual(JSON.parse(calls.at(-1).body), { device_id: 2 });
  assert.equal(calls.at(-1).headers.Authorization, 'Bearer fake-token');
  respond = () => ok([{ ...session, code: '000047' }]);
  assert.equal((await api.sessions(10))[0].code, undefined);
  const record = { id: 7, session_id: 3, member_id: 'member_a', is_present: 1, checked_in_at: new Date().toISOString() };
  respond = () => ok(record);
  assert.equal((await api.checkIn(3,'000047')).id, 7);
  assert.deepEqual(JSON.parse(calls.at(-1).body), { code: '000047' });
  assert.equal(calls.at(-1).path, '/api/attendance-sessions/3/check-in');
  const count = calls.length;
  await assert.rejects(api.checkIn(3,'123'), /6자리/);
  assert.equal(calls.length,count);
  respond = () => ok([{ member_id: 'member_a', name: '팀원', record }]);
  assert.equal((await api.roster(3))[0].record.id,7);
  assert.equal(calls.at(-1).path, '/api/attendance-sessions/3/records');
  respond = () => ok({ ...session, status: 'CLOSED' });
  assert.equal((await api.closeAttendance(3)).status, 'CLOSED');
  assert.equal(calls.at(-1).method,'POST');
  for (const [status, detail] of [[400,'코드 불일치'], [403,'승인된 팀원만 가능'], [409,'출석 시간이 만료되었습니다'], [429,'1분 후 다시 시도하세요']]) {
    respond = () => ({ ok:false,status,json:async()=>({detail}) });
    await assert.rejects(api.checkIn(3,'000047'), err => err.status === status && err.message === detail);
  }
  await assert.rejects(api.simulator(10), /연결되지/);
  assert.ok(!calls.some(c => /\/display$|\/ack$/.test(c.path)));
  respond = () => ok({ info: {version:'0.4.0'}, paths: {'/api/users/me/teams':{}, '/api/attendance-sessions/{session_id}/check-in':{}} });
  assert.equal((await api.capabilities()).attendance,true);
  console.log('PASS: attendance routes, device registration/key non-persistence, leading zeroes, code privacy, roster, expiry/permission/rate limit errors, no device display/ACK calls');
})().catch(error=>{ console.error(error); process.exitCode=1; });
