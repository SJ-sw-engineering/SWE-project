const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const memory = new Map();
const calls = [];
const user = { username: 'test_user', name: '테스트', created_at: null };
const post = { id: 10, title: '테스트', content: '내용', author_name: '테스트', target_size: 2, current_size: 1, category: 'Web', status: 'RECRUITING', created_at: null };
let handler;
const ok = body => ({ ok: true, json: async () => body });
const fail = (status, detail) => ({ ok: false, status, json: async () => ({ detail }) });
const tokens = (n = 1) => ({ access_token: 'access-' + n, refresh_token: 'refresh-' + n, expires_in: 1800, refresh_expires_in: 86400, token_type: 'bearer', user });
const ctx = vm.createContext({ StudyMate: {}, URLSearchParams, AbortController, TypeError, setTimeout, clearTimeout, sessionStorage: { getItem: k => memory.get(k), setItem: (k,v) => memory.set(k,String(v)), removeItem: k => memory.delete(k) }, fetch: async (url, options) => { const call = { path: new URL(url).pathname, ...options }; calls.push(call); return handler(call); } });
vm.runInContext(fs.readFileSync(path.join(__dirname, '../js/server.js'), 'utf8'), ctx);
const api = ctx.StudyMate;
const key = 'studymate.server.auth';
function defaults(call) {
  if (call.path.endsWith('/login')) return ok(tokens());
  if (call.path === '/api/users/me') return ok(user);
  if (call.path.endsWith('/context')) return ok({ is_owner: true, my_application: null });
  return ok(post);
}
(async () => {
  handler = call => ok(user);
  await api.signup({ username: 'test_user', name: '테스트', password: 'password123', password_check: 'password123' });
  assert.deepEqual(Object.keys(JSON.parse(calls.at(-1).body)).sort(), ['name','password','username']);
  handler = defaults;
  await api.login('test_user', 'password123');
  assert.equal(await api.savePost({ title: '제목', content: '내용', category: 'Web', target_size: '2' }), 10);
  assert.equal(calls.at(-1).method, 'POST');
  assert.equal(JSON.parse(calls.at(-1).body).target_size, 2);
  await api.savePost({ title: '수정', content: '내용', category: 'Web', target_size: '3' }, 10);
  assert.equal(calls.at(-1).method, 'PATCH');
  assert.equal((await api.getPost(10)).is_owner, true);
  assert.equal(calls.at(-1).path, '/api/posts/10/context');
  await api.apply(10, '지원');
  assert.deepEqual(JSON.parse(calls.at(-1).body), { message: '지원' });
  await api.decide(2, 'APPROVED');
  assert.equal(calls.at(-1).path, '/api/applications/2');
  handler = () => ok([]);
  for (const fn of [() => api.applicants(10), () => api.myApplications(), () => api.myTeams()]) assert.equal((await fn()).length, 0);
  handler = () => fail(409, '모집 인원이 모두 찼습니다.');
  await assert.rejects(api.apply(10, '지원'), /인원이 모두/);
  handler = () => fail(403, '팀장만 가능합니다.');
  await assert.rejects(api.deletePost(10), /팀장/);
  handler = defaults;
  let releaseRefresh;
  let refreshCount = 0;
  handler = call => {
    if (call.path.endsWith('/refresh')) { refreshCount++; return new Promise(resolve => { releaseRefresh = () => resolve(ok(tokens(2))); }); }
    if (call.path === '/api/users/me' && call.headers.Authorization === 'Bearer access-1') return fail(401, 'expired');
    return defaults(call);
  };
  const first = api.refreshMe(); const second = api.refreshMe();
  // Advance promise continuations without wall-clock waits.
  for (let i=0; i<12 && !releaseRefresh; i++) await Promise.resolve();
  assert.ok(releaseRefresh);
  releaseRefresh(); await Promise.all([first,second]);
  assert.equal(refreshCount, 1);
  assert.equal(JSON.parse(memory.get(key)).refresh_token, 'refresh-2');
  handler = call => call.path.endsWith('/refresh') ? ok(tokens(3)) : defaults(call);
  memory.set(key, JSON.stringify({ ...JSON.parse(memory.get(key)), expires_at: Date.now()-1 }));
  assert.equal(api.me().username, user.username);
  await api.refreshMe();
  assert.equal(JSON.parse(memory.get(key)).token, 'access-3');
  handler = call => call.path.endsWith('/logout') ? ok({detail:'ok'}) : defaults(call);
  await api.logout();
  assert.equal(calls.at(-1).path, '/api/auth/logout');
  assert.deepEqual(JSON.parse(calls.at(-1).body), { refresh_token: 'refresh-3' });
  assert.equal(api.me(), null);
  handler = defaults; await api.login('test_user', 'password123');
  handler = call => call.path.endsWith('/refresh') ? Promise.reject(new TypeError('lost response')) : fail(401, 'expired');
  await assert.rejects(api.refreshMe(), /CORS/);
  assert.equal(api.me(), null);
  const before = calls.filter(c => c.path.endsWith('/refresh')).length;
  await api.refreshMe();
  assert.equal(calls.filter(c => c.path.endsWith('/refresh')).length, before);
  console.log('PASS: signup payload, post CRUD/context, applications, 403/409 detail, concurrent refresh single flight, rotation, lost-refresh cleanup, server logout');
})().catch(error => { console.error(error); process.exitCode=1; });
