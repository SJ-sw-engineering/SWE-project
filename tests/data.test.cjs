  assert.equal(s.status, 'OPEN');
  await assert.rejects(api.startAttendance(second, device), /진행 중/);
  const lcd = await api.simulator(second);
  assert.equal(lcd.code, '000047');
  await api.acknowledge(s.id);
  assert.equal((await api.sessions(second))[0].display_ack, true);
  await login('outsider'); await assert.rejects(api.checkIn(s.id, lcd.code), /승인된/);
  await login('member1');
