  assert.equal((await api.getPost(second)).status, 'CLOSED');
  await assert.rejects(api.savePost({ title: '팀', content: '내용', category: 'Web', target_size: 2 }, second), /현재 인원/);
  await assert.rejects(api.decide(applications[0].id, 'REJECTED'), /이미 처리/);
  await login('outsider'); await assert.rejects(api.apply(second, '지원'), /마감/);
  await assert.rejects(api.deletePost(second), /팀장/);
  await login('leader');
  const device = await api.addSimulator(second);
  const s = await api.startAttendance(second, device);
